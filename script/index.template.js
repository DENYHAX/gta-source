const A_CHECK_OCCUPANT = 0x73F480, A_DO_BULLET_IMPACT = 0x73B550;
const A_INC_BIKERS = 0xB7CD6F, A_INC_TYRES = 0xB7CD70, A_INC_DEAD = 0xB7CD71, A_IGNORE_ENT = 0xB7CD68;
const A_WEAPON_INFO = 0xC8AAB8, WINFO_SIZE = 0x70, O_WI_DAMAGE = 0x22;
const HITGROUP = { 3: 1.0, 4: 1.25, 5: 1.0, 6: 1.0, 7: 0.75, 8: 0.75, 9: 4.0 };   // GTA ped piece -> CS:S hitgroup multiplier
let shotBuf = 0;
function weaponInfoIdx(t) {
  const out = [t];
  if (t >= 22 && t <= 32) for (let k = 0; k < 3; k++) out.push(47 + (t - 22) + k * 11);   // poor / pro / cop skill copies
  return out;
}
function gtaShot(ped, sx, sy, sz, ex, ey, ez, dmg) {
  const slot = Memory.ReadU8(ped + O_ACTIVE_SLOT, false);
  const wp = ped + O_WEAPONS + slot * WEAPON_SIZE;
  const wtype = Memory.ReadU32(wp, false);
  if (wtype !== WEAPONS[cur].gta || wtype < 22 || wtype > 34) return false;
  if (!plos) plos = Memory.Fn.CdeclU8(A_PROCESS_LOS);
  if (!shotBuf) shotBuf = Memory.Allocate(0x80);
  const b = shotBuf, cp = b + 24, pEnt = b + 0x58;
  Memory.WriteFloat(b, sx, false); Memory.WriteFloat(b + 4, sy, false); Memory.WriteFloat(b + 8, sz, false);
  Memory.WriteFloat(b + 12, ex, false); Memory.WriteFloat(b + 16, ey, false); Memory.WriteFloat(b + 20, ez, false);
  Memory.WriteU32(pEnt, 0, false);
  Memory.WriteU8(A_INC_DEAD, 1, false); Memory.WriteU8(A_INC_TYRES, 1, false); Memory.WriteU8(A_INC_BIKERS, 1, false);
  Memory.WriteU32(A_IGNORE_ENT, ped, false);
  let hit = 0;
  try {
    // buildings, vehicles, peds, objects, dummies, !seeThrough, !camIgnore, shootThrough
    hit = plos(b, b + 12, cp, pEnt, 1, 1, 1, 1, 1, 0, 0, 1);
    if (hit) Memory.CallFunctionReturn(A_CHECK_OCCUPANT, 5, 5, pEnt, cp, wtype, b, b + 12);
  } finally {
    Memory.WriteU8(A_INC_DEAD, 0, false); Memory.WriteU8(A_INC_TYRES, 0, false); Memory.WriteU8(A_INC_BIKERS, 0, false);
    Memory.WriteU32(A_IGNORE_ENT, 0, false);
  }
  if (!hit) return true;                          // into the sky
  const ent = Memory.ReadU32(pEnt, false);
  if (ent && (Memory.ReadU8(ent + 0x36, false) & 7) === 3) {   // a ped: CS:S hitgroup damage
    dmg *= HITGROUP[Memory.ReadU8(cp + 0x24, false)] || 1.0;
  }
  // the CS:S damage only for this one call (NPCs keep GTA's damage values)
  const idx = weaponInfoIdx(wtype), saved = idx.map(i => Memory.ReadU16(A_WEAPON_INFO + i * WINFO_SIZE + O_WI_DAMAGE, false));
  const d = Math.max(1, Math.min(65000, Math.round(dmg)));
  for (const i of idx) Memory.WriteU16(A_WEAPON_INFO + i * WINFO_SIZE + O_WI_DAMAGE, d, false);
  try { Memory.CallMethod(A_DO_BULLET_IMPACT, wp, 6, 0, ped, ent, b, b + 12, cp, 0); }
  finally { idx.forEach((i, k) => Memory.WriteU16(A_WEAPON_INFO + i * WINFO_SIZE + O_WI_DAMAGE, saved[k], false)); }
  return true;
}
