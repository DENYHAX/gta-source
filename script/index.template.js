function loadSound(name) {
  if (sounds[name] !== undefined) return sounds[name];
  const pool = [];
  for (let i = 0; i < (name.startsWith("ev\\") ? 2 : 3); i++) {
    let s;
    try { s = AudioStream.Load("cleo\\cssource\\sound\\" + name + ".wav"); } catch (e) { s = undefined; }
    if (!s) break;
    try { s.setType(1); } catch (e) {}     // CLEO 5: SFX stream -> follows GTA's SFX volume and pause
    pool.push(s);
  }
  sounds[name] = pool.length ? { pool, i: 0 } : null;
  return sounds[name];
}
function playSound(name, vol) {
  const snd = loadSound(name);
  if (!snd) return;
  const s = snd.pool[snd.i]; snd.i = (snd.i + 1) % snd.pool.length;
  try { s.setState(0); s.setVolume(vol === undefined ? 1.0 : vol); s.setState(1); } catch (e) {}
}
