// ------------------------- PLAYER MODEL: CS:S PHOENIX ------------------
// t_phoenix retargeted onto the GTA ped skeleton (installer/csmod/build_phoenix.py) as a ped model (PHX_ID). Applied with
// SET_PLAYER_MODEL on foot. While a script takes the controls away (shops, barber, wardrobe, cutscenes) CJ is put
// back (BUILD_PLAYER_MODEL needs CJ's clothes model), and Phoenix returns when the controls come back.
// PHX_ID: ped "csphoenix" (generated; the name "phoenix" is taken by the GTA car!)
let phxCheck = 0, noCtrlSince = 0, lastPlayerModel = -1;
const A_CURR_AREA_PM = 0xB72914;   // CGame::currArea
// Cutscenes use model 1 "csplay" (a hier/clump model), normally rebuilt from CJ's clothes by
// CClothes::RebuildCutscenePlayer(player, modelId) (0x5A8270). A file with the same name in our IMG can NOT replace
// gta3.img's csplay (the first IMG wins), so Phoenix rigged to the csplay face skeleton is its own model (PHX_CUT_ID)
// "csphxcut" (hier, txd csphoenix). RebuildCutscenePlayer is redirected to a stub that clones that clump into
// model 1 exactly like the game's ConstructPedModel does (AddTexDictionaryRef, DeleteRwObject, SetClump(clone),
// RemoveTexDictionaryRef). If csphxcut is not loaded the original function (CJ's clothes) runs.
// PHX_CUT_ID: hier model "csphxcut" (generated)
const A_REBUILD_CS_PLAYER = 0x5A8270, CSP_ORIG = [0x56, 0x8B, 0x74, 0x24, 0x08], CSP_MAGIC = 0x50435343;   // 'CSCP'
const A_MI_PTRS = 0xA9B0C8, A_RPCLUMPCLONE = 0x749F70;
const A_ADDTXDREF = 0x4C4B80, A_REMTXDREF = 0x4C4B90, A_CLUMP_DELETERW = 0x4C4E70, A_CLUMP_SETCLUMP = 0x4C4F70;
// CClumpModelInfo vtable (0x85BD30): +0x20 DeleteRwObject, +0x3C GetAnimFileIndex override (0x4C5710), +0x40 SetClump
const VT_DELETERW = 0x20, VT_SETCLUMP = 0x40;
let cspHook = null;   // null = not tried, false = unavailable, else stub address
function cutsceneHookCode(base) {
  const b = [], L = {}, fix = [];
  const u32 = v => { v >>>= 0; b.push(v & 255, (v >>> 8) & 255, (v >>> 16) & 255, (v >>> 24) & 255); };
  const j8 = (op, l) => { b.push(op, 0); fix.push([b.length - 1, l]); };
  const callAbs = a => { b.push(0xB8); u32(a); b.push(0xFF, 0xD0); };
  b.push(0xA1); u32(A_MI_PTRS + PHX_CUT_ID * 4);          // mov eax,[ms_modelInfoPtrs[csphxcut]]
  b.push(0x85, 0xC0); j8(0x74, 'orig');
  b.push(0x8B, 0x40, 0x1C);                               // mov eax,[eax+0x1C]  (its clump)
  b.push(0x85, 0xC0); j8(0x74, 'orig');
  b.push(0x50); callAbs(A_RPCLUMPCLONE); b.push(0x83, 0xC4, 0x04);   // eax = RpClumpClone(clump)
  b.push(0x85, 0xC0); j8(0x74, 'orig');
  b.push(0x56, 0x57);                                     // push esi, edi
  b.push(0x8B, 0xF0);                                     // mov esi,eax (clone)
  b.push(0x8B, 0x7C, 0x24, 0x10);                         // mov edi,[esp+0x10] (modelId)
  b.push(0x8B, 0x3C, 0xBD); u32(A_MI_PTRS);               // mov edi,[ms_modelInfoPtrs + edi*4]
  b.push(0x85, 0xFF); j8(0x74, 'fail');
  b.push(0x8B, 0xCF); callAbs(A_ADDTXDREF);               // mi->AddTexDictionaryRef()
  b.push(0x8B, 0xCF, 0x8B, 0x01, 0xFF, 0x50, VT_DELETERW); // mi->DeleteRwObject()
  b.push(0x56, 0x8B, 0xCF, 0x8B, 0x01, 0xFF, 0x50, VT_SETCLUMP); // mi->SetClump(clone)
  b.push(0x8B, 0xCF); callAbs(A_REMTXDREF);               // mi->RemoveTexDictionaryRef()
  b.push(0x5F, 0x5E, 0xC3);                               // pop edi, esi; ret
  L.fail = b.length;
  // (unreachable: model 1 is checked at init; the clone is simply leaked)
  b.push(0x5F, 0x5E);
  L.orig = b.length;
  b.push(...CSP_ORIG);                                    // the 5 overwritten bytes: push esi; mov esi,[esp+8]
  b.push(0xE9); const at = b.length; u32(0);
  const rel = ((A_REBUILD_CS_PLAYER + 5) - (base + at + 4)) >>> 0;
  b[at] = rel & 255; b[at + 1] = (rel >>> 8) & 255; b[at + 2] = (rel >>> 16) & 255; b[at + 3] = (rel >>> 24) & 255;
  for (const [p, l] of fix) b[p] = (L[l] - (p + 1)) & 255;
  if (b.length > 0x100) throw new Error("cutscene stub too long");
  return b;
}
// CClothes::ConstructPedModel(modelId, ...) (0x5A81E0) builds CJ's clothes clump INTO the model info of the
// player's current model. CClothes::RebuildPlayer (BUILD_PLAYER_MODEL, new game setup, fat/muscle changes before a
// cutscene) passes the player's model index, so while the player is Phoenix it overwrote the Phoenix model with a
// CJ clump on the wrong skeleton (the twisted, lying CJ). Stub at hook page +0x180: modelId == PHX_ID -> 0, so the
// clothes go into CJ's own model and Phoenix stays intact.
const A_CONSTRUCT_PED = 0x5A81E0, CPM_ORIG = [0x56, 0x57, 0xE8, 0xE9, 0x97, 0xFB, 0xFF], A_TIMER_SUSPEND = 0x5619D0;
// CPed::ProcessBuoyancy calls cBuoyancy::ProcessBuoyancy (0x6C3EF0, thiscall, 4 args) at 0x5E2009. For the player,
// while CS mode runs (flag + frame beat at hook page +0x280/+0x284), the stub at +0x200 answers "not in water":
// no buoyancy force, no swim task (it is stopped), so the CS:S water movement owns the velocity.
const A_CALL_BUOY = 0x5E2009, A_BUOY = 0x6C3EF0;
let buoyFlag = 0, buoyBeat = 0;
function buoyHookInit(base) {
  try {
    const at = base + 0x200, FLAG = base + 0x280, BEAT = base + 0x284;
    const tgt = (A_CALL_BUOY + 5 + Memory.ReadI32(A_CALL_BUOY + 1, true)) >>> 0;
    if (Memory.ReadU8(A_CALL_BUOY, true) !== 0xE8 || (tgt !== A_BUOY && tgt !== at)) { log("[cssource] water hook: unknown code, skipped"); return; }
    const b = [];
    const u32 = v => { v >>>= 0; b.push(v & 255, (v >>> 8) & 255, (v >>> 16) & 255, (v >>> 24) & 255); };
    b.push(0x8B, 0x44, 0x24, 0x04);                          // mov eax, [esp+4]   (entity)
    b.push(0x3B, 0x05); u32(A_PLAYER_PED);                   // cmp eax, [player ped]
    b.push(0x75, 0x00); const j1 = b.length - 1;
    b.push(0x83, 0x3D); u32(FLAG); b.push(0x00);             // cmp dword [FLAG], 0
    b.push(0x74, 0x00); const j2 = b.length - 1;
    b.push(0xA1); u32(BEAT);                                 // mov eax, [BEAT]
    b.push(0x3B, 0x05); u32(A_FRAME_COUNTER);                // cmp eax, [frame counter]
    b.push(0x75, 0x00); const j3 = b.length - 1;
    b.push(0x31, 0xC0, 0xC2, 0x10, 0x00);                    // xor eax, eax; ret 0x10   ("not in water")
    const orig = b.length;
    b.push(0xB8); u32(A_BUOY); b.push(0xFF, 0xE0);           // mov eax, cBuoyancy::ProcessBuoyancy; jmp eax
    for (const j of [j1, j2, j3]) b[j] = orig - (j + 1);
    Memory.WriteU32(FLAG, 0, false);
    for (let i = 0; i < b.length; i++) Memory.WriteU8(at + i, b[i], false);
    if (tgt === A_BUOY) Memory.WriteI32(A_CALL_BUOY + 1, (at - (A_CALL_BUOY + 5)) | 0, true);
    buoyFlag = FLAG; buoyBeat = BEAT;
    log("[cssource] water hook ready");
  } catch (e) { log("[cssource] water hook error: " + e); }
}
function setWaterOverride(on) {
  if (!buoyFlag) return;
  Memory.WriteU32(buoyFlag, on ? 1 : 0, false);
  if (on) Memory.WriteU32(buoyBeat, Memory.ReadU32(A_FRAME_COUNTER, false), false);
}
function clothesHookInit(base) {
  try {
    const at = base + 0x180;
    const cur = []; for (let i = 0; i < 7; i++) cur.push(Memory.ReadU8(A_CONSTRUCT_PED + i, true));
    const isOrig = cur.join() === CPM_ORIG.join();
    const isOurs = cur[0] === 0xE9 && ((A_CONSTRUCT_PED + 5 + Memory.ReadI32(A_CONSTRUCT_PED + 1, true)) >>> 0) === at;
    if (!isOrig && !isOurs) { log("[cssource] clothes hook: unknown code, skipped"); return; }
    const b = [];
    const u32 = v => { v >>>= 0; b.push(v & 255, (v >>> 8) & 255, (v >>> 16) & 255, (v >>> 24) & 255); };
    b.push(0x81, 0x7C, 0x24, 0x04); u32(PHX_ID);                 // cmp dword [esp+4], PHX_ID
    b.push(0x75, 0x00); const j1 = b.length - 1;                  // jne orig
    b.push(0xA1); u32(A_MI_PTRS);                                 // mov eax, [ms_modelInfoPtrs[0]]
    b.push(0x85, 0xC0); b.push(0x74, 0x00); const j2 = b.length - 1;   // no CJ model info -> leave it
    b.push(0x83, 0x78, 0x1C, 0x00); b.push(0x74, 0x00); const j3 = b.length - 1;   // CJ clump not loaded -> leave it
    b.push(0xC7, 0x44, 0x24, 0x04); u32(0);                       // mov dword [esp+4], 0  (build into CJ's model)
    const orig = b.length;
    b.push(0x56, 0x57);                                           // push esi; push edi (overwritten bytes)
    b.push(0xB8); u32(A_TIMER_SUSPEND); b.push(0xFF, 0xD0);       // call CTimer::Suspend
    b.push(0xE9); const jb = b.length; u32(0);                    // jmp 0x5A81E7
    const rel = ((A_CONSTRUCT_PED + 7) - (at + jb + 4)) >>> 0;
    b[jb] = rel & 255; b[jb + 1] = (rel >>> 8) & 255; b[jb + 2] = (rel >>> 16) & 255; b[jb + 3] = (rel >>> 24) & 255;
    for (const j of [j1, j2, j3]) b[j] = orig - (j + 1);
    for (let i = 0; i < b.length; i++) Memory.WriteU8(at + i, b[i], false);
    if (isOrig) {
      Memory.WriteU8(A_CONSTRUCT_PED + 5, 0x90, true); Memory.WriteU8(A_CONSTRUCT_PED + 6, 0x90, true);
      Memory.WriteI32(A_CONSTRUCT_PED + 1, (at - (A_CONSTRUCT_PED + 5)) | 0, true);
      Memory.WriteU8(A_CONSTRUCT_PED, 0xE9, true);
    }
    log("[cssource] clothes hook ready");
  } catch (e) { log("[cssource] clothes hook error: " + e); }
}
function cutsceneHookInit() {
  if (cspHook !== null) return cspHook;
  cspHook = false;
  try {
    const mi1 = Memory.ReadU32(A_MI_PTRS + 4, false) >>> 0, miCut = Memory.ReadU32(A_MI_PTRS + PHX_CUT_ID * 4, false) >>> 0;
    if (!mi1 || !miCut) { log("[cssource] cutscene hook: missing model info (1: " + mi1.toString(16) + ", " + PHX_CUT_ID + ": " + miCut.toString(16) + ")"); return false; }
    const vt = Memory.ReadU32(mi1, false) >>> 0;
    const vDel = Memory.ReadU32(vt + VT_DELETERW, false) >>> 0, vSet = Memory.ReadU32(vt + VT_SETCLUMP, false) >>> 0;
    if (vDel !== A_CLUMP_DELETERW || vSet !== A_CLUMP_SETCLUMP) { log("[cssource] cutscene hook: unknown vtable (" + vDel.toString(16) + ", " + vSet.toString(16) + "), skipped"); return false; }
    const cur = []; for (let i = 0; i < 5; i++) cur.push(Memory.ReadU8(A_REBUILD_CS_PLAYER + i, true));
    let base = 0;
    if (cur[0] === 0xE9) {
      const t = (A_REBUILD_CS_PLAYER + 5 + Memory.ReadI32(A_REBUILD_CS_PLAYER + 1, true)) >>> 0;
      if ((Memory.ReadU32(t + 0x100, false) >>> 0) === CSP_MAGIC) base = t;   // left over from an earlier run: reuse
      else { log("[cssource] cutscene hook: another mod already hooked it, skipped"); return false; }
    } else if ((cur[0] === 0x56 || cur[0] === 0xC3) && cur.slice(1).join() === CSP_ORIG.slice(1).join()) {
      const k = DynamicLibrary.Load("kernel32.dll");
      base = Memory.CallFunctionReturn(k.getProcedure("VirtualAlloc"), 4, 0, 0, 0x1000, 0x3000, 0x40) >>> 0;
      if (!base) { log("[cssource] cutscene hook: VirtualAlloc failed"); return false; }
      Memory.WriteU8(A_REBUILD_CS_PLAYER, 0x56, true);   // undo the old `ret` patch (v32)
    } else { log("[cssource] cutscene hook: unknown code, skipped"); return false; }
    const code = cutsceneHookCode(base);
    for (let i = 0; i < code.length; i++) Memory.WriteU8(base + i, code[i], false);
    Memory.WriteU32(base + 0x100, CSP_MAGIC, false);
    cspHook = base;
    clothesHookInit(base);
    buoyHookInit(base);
    log("[cssource] cutscene hook ready @" + base.toString(16));
  } catch (e) { log("[cssource] cutscene hook error: " + e); cspHook = false; }
  return cspHook;
}
function cutscenePhoenix(on) {
  if (on) {   // keep csphxcut in memory, so it is ready whenever a cutscene starts
    try { if (!Streaming.HasModelLoaded(PHX_CUT_ID)) Streaming.RequestModel(PHX_CUT_ID); } catch (e) {}
  }
  if (!cutsceneHookInit()) return;
  try {
    const want = on ? 0xE9 : 0x56, b = Memory.ReadU8(A_REBUILD_CS_PLAYER, true);
    if (b === want) return;
    if (on) {
      Memory.WriteI32(A_REBUILD_CS_PLAYER + 1, (cspHook - (A_REBUILD_CS_PLAYER + 5)) | 0, true);
      Memory.WriteU8(A_REBUILD_CS_PLAYER, 0xE9, true);
    } else {
      for (let i = 4; i >= 0; i--) Memory.WriteU8(A_REBUILD_CS_PLAYER + i, CSP_ORIG[i], true);
    }
  } catch (e) {}
}
// C3dMarkers::m_aMarkerArray (0xC7DD58, 32 x 0xA0): a marker placed by a script keeps its atomic (+0x48) until the
// first render where it was not placed again. Type +0x50 (1 = cylinder), position = matrix pos +0x30, size +0x68.
// Returns the horizontal distance from the player to the edge of the nearest cylinder (<= 0: inside it).
function nearCylinderMarker(ch) {
  let best = 1e9;
  try {
    const c = ch.getCoordinates();
    for (let i = 0; i < 32; i++) {
      const m = 0xC7DD58 + i * 0xA0;
      if (Memory.ReadU16(m + 0x50, false) !== 1 || !Memory.ReadU32(m + 0x48, false)) continue;
      const x = Memory.ReadFloat(m + 0x30, false), y = Memory.ReadFloat(m + 0x34, false), z = Memory.ReadFloat(m + 0x38, false);
      if (Math.abs(z - c.z) > 3) continue;
      const r = Math.max(0.5, Math.min(3, Memory.ReadFloat(m + 0x68, false) || 1));
      best = Math.min(best, Math.hypot(x - c.x, y - c.y) - r);
    }
  } catch (e) {}
  return best;
}
function playerModel(ch, ped) {
  cutscenePhoenix(!!CFG.playerModel);
  if (!CFG.playerModel) return;
  const t = Date.now(); if (t < phxCheck) return; phxCheck = t + 100;
  const model = Memory.ReadU16(ped + 0x22, false);
  const ctrl = player.isControlOn();
  if (!ctrl) { if (!noCtrlSince) noCtrlSince = t; } else noCtrlSince = 0;
  const area = Memory.ReadU32(A_CURR_AREA_PM, false), csBusy = Memory.ReadU8(0xB5F84C, false) !== 0 || Memory.ReadU8(0xB5F851, false) !== 0;
  if (model !== lastPlayerModel) {                      // diagnostics: who changed the model, and when
    if (CFG.debug) log("[cssource] player model changed: " + lastPlayerModel + " -> " + model + " (ctrl " + ctrl + ", area " + area + ", cutscene " + csBusy + ", vehicle " + ch.isInAnyCar() + ")");
    lastPlayerModel = model;
  }
  if (ch.isInAnyCar()) return;                          // only swap on foot
  if (!ctrl) return;                                    // never swap during a script scene (it breaks the scene's tasks)
  // Shops / barber / tattoo / gym / wardrobe only work with CJ (model 0), and all of them start from a red cylinder
  // marker inside an interior. So CJ comes back BEFORE the player reaches such a marker, Phoenix after walking away.
  const mk = area !== 0 ? nearCylinderMarker(ch) : 1e9;
  if (model === PHX_ID && mk < 2.0) {
    try { player.setModel(0); player.buildModel(); log("[cssource] player model: CJ (shop marker, " + mk.toFixed(1) + " m)"); } catch (e) {}
    return;
  }
  if (model === PHX_ID || mk < 3.5) return;
  if (!Streaming.HasModelLoaded(PHX_ID)) { Streaming.RequestModel(PHX_ID); return; }
  try { player.setModel(PHX_ID); log("[cssource] player model: phoenix"); } catch (e) { log("[cssource] model swap error: " + e); }
}

// ------------------------- BODY ANIMATIONS (mirror / shadow) -------
// Our movement code moves the ped, GTA only animates it. Feed GTA's on-foot task a pad stick that matches our
// speed (always "forward", so GTA never wants to turn the ped away from the view): walk / run / sprint animation.
// bIsStanding is still cleared while moving, so the animation cannot push the ped (velocity stays ours).
function bodyAnims(mv) {
  if (!CFG.bodyAnims) return;
  if (mv.speed < 20) return;                          // resting: GTA's idle
  const sp = mv.speed;
  const stick = sp < 110 ? 50 : 128;                  // walk below ~110 u/s, run above
  Memory.WriteI16(A_PAD0 + 0x02, -stick, false);      // LeftStickY (negative = forward)
  Memory.WriteI16(A_PAD0 + 0x00, 0, false);
  Memory.WriteI16(A_PAD0 + 0x20, sp > 300 ? 255 : 0, false);   // ButtonCross = sprint animation at bhop speeds
}

