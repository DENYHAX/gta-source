// ---- viewmodel drawn on top of the world (like CS:S) ----
// A small code stub replaces Idle's `call RenderEffects` (0x53EAD3). After the world and the effects are drawn it
// clears the depth buffer, switches to a tiny near plane and draws our viewmodel object again by hand
// (UpdateRwMatrix, SetupLighting, Render, RemoveLighting). Walls can no longer cut into the gun, and the world
// keeps a sane near plane (no z-fighting). The normal world copy of the object is made invisible.
// Safety: the stub draws only if the script wrote this frame's CTimer::m_FrameCounter (a dead script = no drawing).
const A_CALL_RFX = 0x53EAD3, A_RENDER_EFFECTS = 0x53E170, A_FRAME_COUNTER = 0xB7CB4C, VMH_MAGIC = 0x4D565343;
let vmHook = null;
function vmHookCode(base) {
  const D = { ent: base + 0x104, beat: base + 0x108, near: base + 0x10C, save: base + 0x110, color: base + 0x114, cnt: base + 0x118,
              sunGlow: base + 0x120, sunFlare: base + 0x124 };
  const b = [];
  const u32 = v => { v >>>= 0; b.push(v & 255, (v >>> 8) & 255, (v >>> 16) & 255, (v >>> 24) & 255); };
  const callAbs = a => { b.push(0xB8); u32(a); b.push(0xFF, 0xD0); };             // mov eax, a ; call eax
  const fixups = [];
  const jcc32 = (op2, label) => { b.push(0x0F, op2); fixups.push([b.length, label]); u32(0); };
  const labels = {};
  callAbs(A_RENDER_EFFECTS);                                                      // original call
  b.push(0xA1); u32(D.ent); b.push(0x85, 0xC0); jcc32(0x84, "done");              // mov eax,[ent]; test; jz done
  b.push(0xA1); u32(D.beat); b.push(0x3B, 0x05); u32(A_FRAME_COUNTER); jcc32(0x85, "done");   // heartbeat == frame?
  b.push(0x53, 0x56, 0x57);                                                       // push ebx, esi, edi
  b.push(0x8B, 0x35); u32(D.ent);                                                 // mov esi,[ent]
  b.push(0x8B, 0x3D); u32(0xC1703C);                                              // mov edi,[Scene.m_pRwCamera]
  b.push(0x85, 0xFF); jcc32(0x84, "pop");                                         // test edi,edi; jz pop
  // no RwObject (GTA only builds it for entities its renderer sees): build it, like CRenderer::SetupEntityVisibility
  b.push(0x8B, 0x46, 0x18, 0x85, 0xC0); jcc32(0x85, "hasrw");                       // mov eax,[esi+0x18]; test; jnz
  b.push(0x8B, 0xCE, 0x8B, 0x06, 0xFF, 0x50, 0x1C);                               // CreateRwObject()
  b.push(0x8B, 0x46, 0x18, 0x85, 0xC0); jcc32(0x84, "pop");                       // still none -> skip
  labels.hasrw = b.length;
  b.push(0x8B, 0xCE); callAbs(0x446F90);                                          // CEntity::UpdateRwMatrix
  b.push(0x8B, 0xCE); callAbs(0x532B00);                                          // CEntity::UpdateRwFrame
  b.push(0x8B, 0x87); u32(0x80); b.push(0xA3); u32(D.save);                       // save camera->nearPlane
  b.push(0x57); callAbs(0x7EE180); b.push(0x83, 0xC4, 0x04);                      // RwCameraEndUpdate
  b.push(0xFF, 0x35); u32(D.near); b.push(0x57); callAbs(0x7EE1D0); b.push(0x83, 0xC4, 0x08);   // SetNearClipPlane(tiny)
  b.push(0x57); callAbs(0x7EE190); b.push(0x83, 0xC4, 0x04);                      // RwCameraBeginUpdate
  b.push(0x6A, 0x02, 0x68); u32(D.color); b.push(0x57); callAbs(0x7EE340); b.push(0x83, 0xC4, 0x0C);   // RwCameraClear(Z)
  callAbs(0x734650);                                                              // DefinedState()
  b.push(0x8B, 0xCE, 0x8B, 0x06, 0xFF, 0x50, 0x4C, 0x0F, 0xB6, 0xD8);             // ebx = SetupLighting()
  b.push(0x8B, 0xCE); callAbs(0x534310);                                          // CEntity::Render (skips CObject's bDoNotRender check)
  b.push(0x53, 0x8B, 0xCE, 0x8B, 0x06, 0xFF, 0x50, 0x50);                         // RemoveLighting(ebx)
  b.push(0x57); callAbs(0x7EE180); b.push(0x83, 0xC4, 0x04);                      // EndUpdate
  b.push(0xFF, 0x35); u32(D.save); b.push(0x57); callAbs(0x7EE1D0); b.push(0x83, 0xC4, 0x08);   // restore near plane
  b.push(0x57); callAbs(0x7EE190); b.push(0x83, 0xC4, 0x04);                      // BeginUpdate
  labels.pop = b.length; b.push(0x5F, 0x5E, 0x5B);                                // pop edi, esi, ebx
  labels.done = b.length; b.push(0xC3);                                           // ret
  for (const [at, l] of fixups) { const rel = (labels[l] - (at + 4)) >>> 0; b[at] = rel & 255; b[at + 1] = (rel >>> 8) & 255; b[at + 2] = (rel >>> 16) & 255; b[at + 3] = (rel >>> 24) & 255; }
  if (b.length > 0x100) throw new Error("stub too long");
  return { bytes: b, D };
}
function vmHookInit() {
  if (vmHook !== null) return vmHook;
  vmHook = false;
  if (!CFG.vmOnTop) return false;
  try {
    if (Memory.ReadU8(A_CALL_RFX, true) !== 0xE8) { log("[cssource] vm hook: unknown code, skipped"); return false; }
    const target = (A_CALL_RFX + 5 + Memory.ReadI32(A_CALL_RFX + 1, true)) >>> 0;
    let base;
    if (target === A_RENDER_EFFECTS) {
      const k = DynamicLibrary.Load("kernel32.dll");
      base = Memory.CallFunctionReturn(k.getProcedure("VirtualAlloc"), 4, 0, 0, 0x1000, 0x3000, 0x40) >>> 0;   // RWX
      if (!base) { log("[cssource] vm hook: VirtualAlloc failed"); return false; }
    } else if (Memory.ReadU32(target + 0x100, false) >>> 0 === VMH_MAGIC) {
      base = target;                                   // left over from an earlier run of this script: reuse
    } else { log("[cssource] vm hook: another mod already hooked the RenderEffects call, skipped"); return false; }
    const { bytes, D } = vmHookCode(base);
    Memory.WriteU32(D.ent, 0, false);                  // nothing to draw until the script says so
    for (let i = 0; i < bytes.length; i++) Memory.WriteU8(base + i, bytes[i], false);
    Memory.WriteU32(base + 0x100, VMH_MAGIC, false);
    Memory.WriteFloat(D.near, CFG.vmNearClip, false);
    Memory.WriteU32(D.color, 0, false);
    if (target === A_RENDER_EFFECTS) Memory.WriteI32(A_CALL_RFX + 1, (base - (A_CALL_RFX + 5)) | 0, true);
    vmHook = D;
    mirrorHookInit(base);
    log("[cssource] vm hook ready @" + base.toString(16));
  } catch (e) { log("[cssource] vm hook error: " + e); vmHook = false; }
  return vmHook;
}
