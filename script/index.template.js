    Memory.WriteU32(b + 0x58, 0, false); Memory.WriteU32(A_IGNORE_ENT, ped, false);
    let hit = 0;
    try { hit = plos(b, b + 12, b + 24, b + 0x58, 1, 1, 1, 1, 0, 0, 0, 1); } finally { Memory.WriteU32(A_IGNORE_ENT, 0, false); }
    if (!hit) return null;
