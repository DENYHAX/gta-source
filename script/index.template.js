// ---- collision probes: CWorld::ProcessLineOfSight (0x56BA00) -> surface normals (slopes, surf ramps, walls)
const A_PROCESS_LOS = 0x56BA00;
let rayBuf = 0, plos = null;
function ray(x0, y0, z0, x1, y1, z1) {
  if (!rayBuf) { rayBuf = Memory.Allocate(0x60); plos = Memory.Fn.CdeclU8(A_PROCESS_LOS); }
  const b = rayBuf;
  Memory.WriteFloat(b, x0, false); Memory.WriteFloat(b + 4, y0, false); Memory.WriteFloat(b + 8, z0, false);
  Memory.WriteFloat(b + 12, x1, false); Memory.WriteFloat(b + 16, y1, false); Memory.WriteFloat(b + 20, z1, false);
  Memory.WriteU32(b + 0x48, 0, false);
  // origin, target, CColPoint*, CEntity**, buildings, vehicles, peds, objects, dummies, seeThrough, camIgnore, shootThrough
  if (!plos(b, b + 12, b + 24, b + 0x48, 1, 1, 0, 1, 0, 0, 0, 0)) return null;
  const cp = b + 24;
  return { px: Memory.ReadFloat(cp, false), py: Memory.ReadFloat(cp + 4, false), pz: Memory.ReadFloat(cp + 8, false),
           nx: Memory.ReadFloat(cp + 16, false), ny: Memory.ReadFloat(cp + 20, false), nz: Memory.ReadFloat(cp + 24, false) };
}
const CAP_R = 0.35, CAP_H = 0.65, CONTACT = 0.09, WALL_CONTACT = 0.15;   // CJ ~ capsule: centre 1 m above the feet
let lastSurf = null;
function probe(c, wx, wy) {
  const out = [];
  const hs = Math.hypot(vel.x, vel.y);
  const hx = hs > 1 ? vel.x / hs : 0, hy = hs > 1 ? vel.y / hs : 0;
  const tests = [[0, 0, -1.45]];
  if (hs > 1) {
    tests.push([hx * 1.0, hy * 1.0, 0]); tests.push([hx * 0.8, hy * 0.8, -1.2]); tests.push([hx * 0.8, hy * 0.8, 0.9]);
    tests.push([-hy * 0.8, hx * 0.8, 0]); tests.push([hy * 0.8, -hx * 0.8, 0]);      // walls beside us (running along them)
    tests.push([hx * 1.0, hy * 1.0, -0.5, -0.5]);                                     // low walls: knee height (0.5 m above the feet)
  }
  if (wx || wy) { tests.push([wx * 1.0, wy * 1.0, 0]); tests.push([wx * 1.0, wy * 1.0, -0.5, -0.5]); }   // where the keys push us
  if (lastSurf) tests.push([-lastSurf.nx * 1.5, -lastSurf.ny * 1.5, -lastSurf.nz * 1.5]);
  for (const t of tests) {
    const z0 = c.z + (t[3] || 0);                       // optional start height offset (knee rays: horizontal at -0.5)
    const h = ray(c.x, c.y, z0, c.x + t[0], c.y + t[1], z0 + (t[3] ? 0 : t[2]));
    if (!h) continue;
    const nl = Math.hypot(h.nx, h.ny, h.nz); if (nl < 0.5) continue;
    const nx = h.nx / nl, ny = h.ny / nl, nz = h.nz / nl;
    const d = (c.x - h.px) * nx + (c.y - h.py) * ny + (c.z - h.pz) * nz - (CAP_R + CAP_H * Math.abs(nz));
    if (d < 0.35 && !out.some(o => o.nx * nx + o.ny * ny + o.nz * nz > 0.99)) out.push({ nx, ny, nz, d, hz: h.pz - c.z });
  }
  return out;
}
