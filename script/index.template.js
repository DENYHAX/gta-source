      const j8 = (op, l) => { b.push(op, 0); fix.push([b.length - 1, l]); };
      b.push(0x31, 0xD2);                                               // xor edx,edx
      b.push(0xA1); u32(FLAG2); b.push(0x85, 0xC0); j8(0x74, 'go');     // flag?
      b.push(0xA1); u32(BEAT2); b.push(0x3B, 0x05); u32(A_FRAME_COUNTER); j8(0x75, 'go');
      b.push(0x8B, 0x15); u32(A_PLAYER_PED); b.push(0x85, 0xD2); j8(0x74, 'go');
      b.push(0xF6, 0x82); u32(O_PEDFLAGS3); b.push(0x02); j8(0x75, 'nohide');   // already hidden by GTA: leave it
      b.push(0x80, 0x8A); u32(O_PEDFLAGS3); b.push(0x02); j8(0xEB, 'go');      // or byte [edx+0x474],2
      L.nohide = b.length; b.push(0x31, 0xD2);
      L.go = b.length; b.push(0x52); b.push(0xB8); u32(target); b.push(0xFF, 0xD0); b.push(0x5A);
      b.push(0x85, 0xD2); j8(0x74, 'end');
      b.push(0x80, 0xA2); u32(O_PEDFLAGS3); b.push(0xFD);               // and byte [edx+0x474],~2
