// ---- ramp / surf catch-up ----
// CPhysical::ProcessCollision puts the ped back to the start of the frame when CheckCollision finds a hit, and a
// standing ped gets snapped to the ground: while sliding along a ramp (or launching off its crest) GTA swallows
// whole frames of our movement, which feels like a delay. Our velocity is the truth: if the ped moved less along
// the expected displacement than it should have, move it the rest of the way (only along that displacement,
// never into the ramp, and only if a ray says the way is free).
let rampTrack = null, rampGrace = 0, rcFrames = 0, rcFixed = 0, rcSum = 0, rcLogT = 0;
function rampCatchup(c, ts) {
  const tr = rampTrack; rampTrack = null;
  if (!tr || !CFG.rampCatchup) return c;
  rcFrames++;
  const ax = c.x - tr.x, ay = c.y - tr.y, az = c.z - tr.z;
  const ee = tr.ex * tr.ex + tr.ey * tr.ey + tr.ez * tr.ez;
  let out = c;
  if (ee > 0.0004) {
    const along = (ax * tr.ex + ay * tr.ey + az * tr.ez) / ee;
    if (along < 0.85 && along > -0.5) {
      const k = 1 - Math.max(along, 0), cx = tr.ex * k, cy = tr.ey * k, cz = tr.ez * k, cl = Math.sqrt(ee) * k;
      if (cl < 1.5) {
        const ux = cx / cl, uy = cy / cl, uz = cz / cl;
        const tgt = { x: c.x + cx, y: c.y + cy, z: c.z + cz };
        if (capsuleClear(c, tgt, ux, uy, uz, cl)) {
          out = tgt;
          ch_setPos(out);
          rcFixed++; rcSum += k;
        }
      }
    }
  }
  const t = Date.now();
  if (t > rcLogT && rcFrames) {
    if (rcFixed && CFG.debug) log("[cssource] ramp catchup: " + rcFixed + "/" + rcFrames + " frames, avg " + (rcSum / rcFixed * 100).toFixed(0) + "% restored");
    rcLogT = t + 1000; rcFrames = 0; rcFixed = 0; rcSum = 0;
  }
  return out;
}
// would the capsule at `t` overlap something? (same capsule metric as probe(); rays along the move and down)
function capsuleClear(c, t, ux, uy, uz, cl) {
  const L = cl + 1.0;
  const tests = [[c.x, c.y, c.z, c.x + ux * L, c.y + uy * L, c.z + uz * L], [t.x, t.y, t.z, t.x, t.y, t.z - 1.6]];
  for (const r of tests) {
    const h = ray(r[0], r[1], r[2], r[3], r[4], r[5]);
    if (!h) continue;
    const nl = Math.hypot(h.nx, h.ny, h.nz); if (nl < 0.5) return false;
    const nx = h.nx / nl, ny = h.ny / nl, nz = h.nz / nl;
    const cap = CAP_R + CAP_H * Math.abs(nz);
    const d = (t.x - h.px) * nx + (t.y - h.py) * ny + (t.z - h.pz) * nz - cap;
    const dc = (c.x - h.px) * nx + (c.y - h.py) * ny + (c.z - h.pz) * nz - cap;   // where we are now (GTA's own overlap)
    if (d < Math.min(dc, 0) - 0.01) return false;
  }
  return true;
}
function ch_setPos(p) { try { player.getChar().setCoordinatesNoOffset(p.x, p.y, p.z); } catch (e) {} }
// ---- water (Source CGameMovement: CheckWater / WaterMove / CheckWaterJump / WaterJump) ----
// Water level like Source: 1 = feet wet (normal movement), 2 = waist deep (swimming), 3 = eyes under water.
// GTA's own buoyancy and swim task are switched off for the player while CS mode runs (see buoyHookInit), so the
// velocity stays ours; drowning still goes through GTA's CPlayerPed::HandlePlayerBreath (and its breath bar).
const A_GET_WATER_LEVEL = 0x6EB690, A_FX_SPLASH = 0x4A1070, A_G_FX = 0xA9AE00, A_HUD_LAST_BREATH = 0xBAA3FC, A_TIME_MS = 0xB7CB84;
let gwlFn = null, gwlBuf = 0, waterJumpT = 0, wjVel = { x: 0, y: 0 }, lastWl = 0, swimT = 0, swimI = 0, waterInfo = { wl: 0, wz: 0 };
const f2i = (() => { const dv = new DataView(new ArrayBuffer(4)); return v => { dv.setFloat32(0, v, true); return dv.getInt32(0, true); }; })();
function waterLevelAt(x, y, z) {   // CWaterLevel::GetWaterLevel(x, y, z, &level, bTouchingWater, normals) -> surface z or null
  try {
    if (!gwlFn) { gwlBuf = Memory.Allocate(16); gwlFn = Memory.Fn.CdeclU8(A_GET_WATER_LEVEL); }
    return gwlFn(f2i(x), f2i(y), f2i(z), gwlBuf, 1, 0) ? Memory.ReadFloat(gwlBuf, false) : null;
  } catch (e) { return null; }
}
function waterState(c, ducking) {
  const wz = waterLevelAt(c.x, c.y, c.z);
  if (wz === null) return { wl: 0, wz: 0 };
  const feet = c.z - (CAP_H + CAP_R);
  let wl = 0;
  if (wz > feet + 1 * U2M) wl = 1;
  if (wz > feet + (ducking ? 27 : 36) * U2M) wl = 2;            // waist: half of the CS:S hull (72 / 54 ducked)
  if (wz > c.z + eyeZ) wl = 3;
  return { wl, wz };
}
function checkWaterJump(c, yawDeg, ducking) {   // waist deep against a ledge you can climb -> pop out (vz 256)
  if (waterJumpT > 0 || vel.z < -180) return;
  const y0 = yawDeg * DEG, fx = -Math.sin(y0), fy = Math.cos(y0);
  if (Math.hypot(vel.x, vel.y) > 1 && vel.x * fx + vel.y * fy < 0) return;   // backing into the water
  const feet = c.z - (CAP_H + CAP_R), waist = feet + (ducking ? 27 : 36) * U2M, L = CAP_R + 24 * U2M;
  const h1 = ray(c.x, c.y, waist, c.x + fx * L, c.y + fy * L, waist);
  if (!h1) return;
  const nl = Math.hypot(h1.nx, h1.ny);
  if (nl < 0.3) return;
  const top = c.z + eyeZ + 8 * U2M;
  if (ray(c.x, c.y, top, c.x + fx * L, c.y + fy * L, top)) return;           // the ledge is too high
  const h3 = ray(c.x + fx * L, c.y + fy * L, top, c.x + fx * L, c.y + fy * L, top - 12);
  if (!h3 || h3.nz / (Math.hypot(h3.nx, h3.ny, h3.nz) || 1) < 0.7) return;    // nothing to stand on
  vel.z = 256; wjVel = { x: -h1.nx / nl * 50, y: -h1.ny / nl * 50 }; waterJumpT = 2.0;
}
function waterMove(TICK, fmove, smove, yawDeg, swimUp, maxs, accel, p) {
  const y = yawDeg * DEG, pt = pitch * DEG;
  const f = { x: -Math.sin(y) * Math.cos(pt), y: Math.cos(y) * Math.cos(pt), z: Math.sin(pt) };   // view forward (with pitch)
  const r = { x: Math.cos(y), y: Math.sin(y) };
  const w = { x: f.x * fmove + r.x * smove, y: f.y * fmove + r.y * smove, z: f.z * fmove };
  if (swimUp) w.z += maxs;
  else if (!fmove && !smove) w.z -= 60;                                       // drift towards the bottom
  else w.z += Math.min(Math.max(fmove * f.z * 2, 0), maxs);                   // exaggerate upward movement
  let wishspeed = Math.hypot(w.x, w.y, w.z);
  if (wishspeed > maxs) { const k = maxs / wishspeed; w.x *= k; w.y *= k; w.z *= k; wishspeed = maxs; }
  wishspeed *= 0.8;
  const speed = Math.hypot(vel.x, vel.y, vel.z);
  let newspeed = 0;
  if (speed > 0) {
    newspeed = speed - TICK * speed * p.friction;                           // water friction (sv_friction)
    if (newspeed < 0.1) newspeed = 0;
    vel.x *= newspeed / speed; vel.y *= newspeed / speed; vel.z *= newspeed / speed;
  }
  if (wishspeed >= 0.1) {
    const add = wishspeed - newspeed;
    if (add > 0) {
      const wl_ = Math.hypot(w.x, w.y, w.z) || 1;
      const acc = Math.min(accel * wishspeed * TICK, add);
      vel.x += acc * w.x / wl_; vel.y += acc * w.y / wl_; vel.z += acc * w.z / wl_;
    }
  }
}
// Same as CPlayerPed::HandlePlayerBreath(true, 1): CPlayerData (ped +0x480) m_fBreath +0x44 goes down by the GTA
// timestep, and bit 0x80 of +0x34 (m_bRequireHandleBreath) is cleared so CPlayerPed::ProcessControl does not refill
// it in the same frame. Out of air: CS:S style drowning, 10 damage per second.
let drownAcc = 0;
function drown(ch, ped, dt) {
  try {
    const pd = Memory.ReadU32(ped + 0x480, false) >>> 0;
    if (!pd) return;
    const ts = Memory.ReadFloat(A_TIMESTEP, false);
    const br = Memory.ReadFloat(pd + 0x44, false);
    if (br > 0) { Memory.WriteFloat(pd + 0x44, Math.max(0, br - ts), false); drownAcc = 0; }
    else {
      drownAcc += dt;
      if (drownAcc >= 1) { drownAcc -= 1; ch.setHealth(Math.max(0, ch.getHealth() - 10)); }
    }
    Memory.WriteU32(pd + 0x34, Memory.ReadU32(pd + 0x34, false) & ~0x80, false);
  } catch (e) {}
}
function waterEffects(ch, ped, c, wat, dt, onGround) {
  const sp = Math.hypot(vel.x, vel.y, vel.z);
  if (wat.wl >= 2 && lastWl < 2 && vel.z < -150) {                         // splash on entry
    playSound("splash" + (1 + Math.floor(Math.random() * 3)), Math.min(1, -vel.z / 600));
    try { const b = Memory.Allocate(12); Memory.WriteFloat(b, c.x, false); Memory.WriteFloat(b + 4, c.y, false); Memory.WriteFloat(b + 8, wat.wz, false);
          Memory.CallMethod(A_FX_SPLASH, A_G_FX, 1, 0, b); Memory.Free(b); } catch (e) {}
  } else if (wat.wl === 1 && lastWl === 0 && vel.z < -200) playSound("slosh" + (1 + (stepI++ % 4)), 0.5);
  if (wat.wl >= 2 && !onGround) {                                          // swim strokes
    swimT -= dt;
    if (sp > 60 && swimT <= 0) { swimT = 0.8; playSound("wade" + (1 + (swimI++ % 4)), 0.45); }
  }
  if (wat.wl === 3) drown(ch, ped, dt);       // eyes under water: GTA's breath bar runs down, then you drown
  else drownAcc = 0;
  // CHud::DrawPlayerInfo starts the breath bar only for a ped with a swim task (ours has none) and then keeps it on
  // while breath < max as long as m_LastBreathTime (0xBAA3FC) is younger than 500 ms: keep it fresh while swimming.
  if (wat.wl >= 2) { try { Memory.WriteU32(A_HUD_LAST_BREATH, Memory.ReadU32(A_TIME_MS, false), false); } catch (e) {} }
  if (CFG.debug && wat.wl !== lastWl) log("[cssource] water level " + lastWl + " -> " + wat.wl + " (surface " + wat.wz.toFixed(2) + ")");
  lastWl = wat.wl;
}
let tickAcc = 0;
function movement(ch, ped, dt, ts, frozen, yawStart) {
  const p = preset();
  const TICK = 1 / p.tickrate;
  const gx = Memory.ReadFloat(ped + O_MOVESPEED, false) * GTA_TO_UPS;
  const gy = Memory.ReadFloat(ped + O_MOVESPEED + 4, false) * GTA_TO_UPS;
  const gz = Memory.ReadFloat(ped + O_MOVESPEED + 8, false) * GTA_TO_UPS;
  const flags = Memory.ReadU8(ped + O_PEDFLAGS, false);
  const gtaStanding = (flags & 1) !== 0;
  let c = ch.getCoordinates();
  c = rampCatchup(c, ts);

  const fmove = frozen ? 0 : (held(VK.W) ? 400 : 0) - (held(VK.S) ? 400 : 0);
  const smove = frozen ? 0 : (held(VK.D) ? 400 : 0) - (held(VK.A) ? 400 : 0);
  let pwx = 0, pwy = 0;
  if (fmove || smove) {
    const y0 = yaw * DEG, vx = -Math.sin(y0) * fmove + Math.cos(y0) * smove, vy = Math.cos(y0) * fmove + Math.sin(y0) * smove;
    const l = Math.hypot(vx, vy); pwx = vx / l; pwy = vy / l;
  }

  // surfaces we touch
  const all = probe(c, pwx, pwy);
  let ground = null, steep = null;
  for (const k of all) {
    // StayOnGround: while walking keep ground contact over small dips (Source does the same)
    if (k.nz >= 0.7) { if (k.d < (wasOnGround ? 0.3 : CONTACT) && (!ground || k.nz > ground.nz)) ground = k; }
    else if (k.nz > -0.7) { if (k.d < CONTACT && (!steep || k.d < steep.d)) steep = k; }
  }
  const cts = all.filter(k => k.d < CONTACT);
  lastSurf = (steep && steep.nz > 0.05) ? steep : null;
  let onGround = vel.z <= 140 && (ground !== null || (gtaStanding && !steep));
  if (onGround && !ground) ground = { nx: 0, ny: 0, nz: 1, d: 0 };

  // walls (Source TryPlayerMove): only the velocity INTO the wall is removed, the part along it is kept,
  // so you slide along walls - and running into one at an angle with W held is even a bit faster, like in CS:S.
  const walls = all.filter(k => Math.abs(k.nz) < 0.7 && k !== steep && k.d < WALL_CONTACT && k.hz > -0.6);   // kerbs/steps (< 0.4 m) are GTA's step-up, not walls
  // GTA stopped us on something the rays did not see (props, poles, cars, peds): the lost velocity gives
  // the normal of that obstacle -> clip against it instead of taking over GTA's (stuck) velocity.
  // Two signals: GTA's velocity after its collision step, and how far the ped really moved since last frame.
  // A loss that is just a parallel scale-down (GTA's air drag / speed limits at boost speeds) is NOT a wall.
  if (lastWritten && !steep && !walls.length) {
    const lw = Math.hypot(lastWritten.x, lastWritten.y);
    const blockedBy = (ax, ay, ex, ey) => {        // actual vs expected (same units) -> wall normal or null
      const el = Math.hypot(ex, ey); if (el < 1e-6) return null;
      const along = (ax * ex + ay * ey) / el, perp = Math.abs(ax * ey - ay * ex) / el;
      if (along > el * Math.pow(0.97, ts)) return null;                 // not slowed
      if (along > el * 0.15 && perp < el * 0.06) return null;           // only scaled down, same direction: drag, not a wall
      const nx = ax - ex, ny = ay - ey, nl = Math.hypot(nx, ny);
      return nl > el * 0.03 ? { nx: nx / nl, ny: ny / nl, nz: 0, d: 0 } : null;
    };
    let wn = null;   // (pwx, pwy) = wish direction
    if (lw > 1) wn = blockedBy(gx, gy, lastWritten.x, lastWritten.y);
    if (!wn && lastPos && lw > 30) {               // GTA pushed the position back without touching the velocity
      const ex = lastWritten.x * UPS_TO_GTA * lastTs, ey = lastWritten.y * UPS_TO_GTA * lastTs;
      const ax = c.x - lastPos.x, ay = c.y - lastPos.y;
      if (Math.hypot(ax, ay) < 5) {
        const along = (ax * ex + ay * ey) / Math.hypot(ex, ey);
        if (along < Math.hypot(ex, ey) * 0.6) wn = blockedBy(ax, ay, ex, ey);
      }
    }
    // a wrong normal (GTA shoving us out of a thin fence) must not glue us to it: if the keys push away
    // from the inferred obstacle, ignore it (that was the "fence doesn't let go" feeling)
    if (wn && (pwx || pwy) && pwx * wn.nx + pwy * wn.ny > -0.2) wn = null;
    if (wn) walls.push(wn);
  }
  const boost = !frozen && held(VK.MMB);

  const ducking = !frozen && (held(VK.CTRL) || now < wheelDuckUntil);
  const walking = held(VK.SHIFT);
  let maxs = p.runspeed || maxSpeed();
  if (zoom > 0 && WEAPONS[cur].maxspeedZoom) maxs = Math.min(maxs, WEAPONS[cur].maxspeedZoom);
  if (walking) maxs *= 0.52;

  const jumpHeld = !frozen && (p.autobhop ? (held(VK.SPACE) || wheelJump) : (pressed(VK.SPACE) || wheelJump));
  // ---- RNGFix (rngfix-master, the CS:S bhop server plugin) ----
  // edge bug: GTA stopped our fall on an edge the probes missed -> with jump held you always get the jump
  if (!onGround && !steep && vel.z < -50 && jumpHeld && (gtaStanding || gz > vel.z * 0.3)) {
    onGround = true; ground = ground || { nx: 0, ny: 0, nz: 1, d: 0 };
  }
  // landing on an incline: downhill -> always the boost (slopefix); uphill -> never lose speed;
  // if the deflected Z velocity is > 140 it is a slide, not a landing (NON_JUMP_VELOCITY)
  if (onGround && !wasOnGround && ground) {
    const back = vel.x * ground.nx + vel.y * ground.ny + vel.z * ground.nz;
    if (back < 0) {
      const nvx = vel.x - ground.nx * back, nvy = vel.y - ground.ny * back, nvz = vel.z - ground.nz * back;
      if (nvz > 140) { vel.x = nvx; vel.y = nvy; vel.z = nvz; onGround = false; }
      else if (nvx * nvx + nvy * nvy > vel.x * vel.x + vel.y * vel.y) { vel.x = nvx; vel.y = nvy; }
    }
  }

  const wat = waterState(c, ducking); waterInfo = wat;
  const swimUp = !frozen && (held(VK.SPACE) || wheelJump);
  if (wat.wl === 2) checkWaterJump(c, yaw, ducking);
  if (waterJumpT > 0 && wat.wl === 0) waterJumpT = 0;

  // fixed tickrate (shavit servers: 100 tick), view yaw interpolated over the ticks of this frame
  tickAcc += dt;
  let steps = Math.floor(tickAcc / TICK);
  if (steps > 12) { steps = 12; tickAcc = 0; } else tickAcc -= steps * TICK;
  const dy = angDiff(yawStart, yaw);
  let jumped = false, jumpUsed = false;
  for (let i = 0; i < steps; i++) {
    const y = (yawStart + dy * (i + 1) / steps) * DEG;
    const fx = -Math.sin(y), fy = Math.cos(y), rx = Math.cos(y), ry = Math.sin(y);
    const wvx = fx * fmove + rx * smove, wvy = fy * fmove + ry * smove;
    let wishspeed = Math.hypot(wvx, wvy);
    let wx = 0, wy = 0;
    if (wishspeed > 0) { wx = wvx / wishspeed; wy = wvy / wishspeed; }
    if (wishspeed > maxs) wishspeed = maxs;

    if (waterJumpT > 0) {                       // WaterJump: climbing out over a ledge
      vel.x = wjVel.x; vel.y = wjVel.y;
      waterJumpT -= TICK; if (waterJumpT < 0) waterJumpT = 0;
      if (wat.wl <= 1) vel.z -= CFG.gravity * TICK;
      onGround = false;
    } else if (wat.wl >= 2) {                     // swimming (WaterMove): no gravity, water friction, swim where you look
      if (swimUp) { vel.z = 100; onGround = false; }        // CheckJumpButton in water: swim up at 100 u/s
      waterMove(TICK, fmove, smove, yawStart + dy * (i + 1) / steps, swimUp, maxs, p.accelerate, p);
      if (onGround && vel.z < 0) vel.z = 0;
    } else if (onGround && jumpHeld && !jumpUsed) {
      vel.z = JUMP_SPEED; onGround = false; jumped = true; jumpUsed = !p.autobhop;
    }
    if (waterJumpT > 0 || wat.wl >= 2) {
      // handled above
    } else if (onGround) {
      vel.z = 0;
      friction(TICK);
      accelerate(wx, wy, ducking ? wishspeed * 0.34 : wishspeed, p.accelerate, TICK);
    } else {
      airAccelerate(wx, wy, wishspeed, p.airaccelerate, TICK);
      vel.z -= CFG.gravity * TICK;
      if (steep) clipVelocity(steep);            // surf: slide along steep ramps
      for (const k of cts) if (k.nz < -0.7) clipVelocity(k);   // ceiling
      // sliding UP a walkable slope faster than 140 u/s counts as airborne in Source; TryPlayerMove keeps the
      // velocity on the slope plane, so at the crest you get launched upwards
      for (const k of cts) if (k.nz >= 0.7 && k.nz < 0.999) clipVelocity(k);
    }
    if (boost) {                                 // MOUSE3 speed boost along the view direction
      const before = Math.hypot(vel.x, vel.y);
      vel.x += fx * CFG.boostAccel * TICK; vel.y += fy * CFG.boostAccel * TICK;
      const after = Math.hypot(vel.x, vel.y), lim = Math.max(before, CFG.boostMax);
      if (after > lim) { vel.x *= lim / after; vel.y *= lim / after; }
    }
    for (const k of walls) clipVelocity(k);      // every tick, like Source
    if (!onGround && vel.z < minAirVz) minAirVz = vel.z;
  }
  if (onGround && steep) clipVelocity(steep);

  // fall damage, footsteps
  if (onGround && !wasOnGround) {
    if (CFG.fallDamage && -minAirVz > CFG.maxFallSafe) {
      const dmg = Math.round((-minAirVz - CFG.maxFallSafe) * 100 / (CFG.maxFallFatal - CFG.maxFallSafe));
      ch.setHealth(Math.max(ch.getHealth() - dmg, 0));
    }
    if (minAirVz < -200 && wat.wl < 2) playSound((wat.wl ? "slosh" : "step") + (1 + (stepI++ % 4)), 0.5);
    minAirVz = 0;
  }
  if (onGround && wat.wl < 2 && Math.hypot(vel.x, vel.y) >= 150 && !ducking) {
    stepT -= dt;
    if (stepT <= 0) { stepT = 0.35; playSound((wat.wl ? "slosh" : "step") + (1 + (stepI++ % 4)), 0.4); }
  }
  waterEffects(ch, ped, c, wat, dt, onGround);
  wasOnGround = onGround && !jumped;

  if (jumped) ch.setCoordinatesNoOffset(c.x, c.y, c.z + 0.02);   // before the velocity write (it zeroes velocity)
  // standing still on the ground: leave GTA's bIsStanding alone and let it hold the ped, so scripts see a
  // "stopped" player (shop entrances, the barber's chair, mission markers use IsPedStopped -> bIsStanding)
  // If GTA does not set bIsStanding by itself within 0.3 s of standing still, set it ourselves.
  const calm = onGround && !jumped && !fmove && !smove && Math.hypot(vel.x, vel.y) < 5 && wat.wl < 2 && !waterJumpT;
  if (calm && !gtaStanding && ground !== null) { calmT += dt; if (calmT > 0.3) Memory.WriteU8(ped + O_PEDFLAGS, flags | 1, false); }
  else if (!calm) calmT = 0;
  const resting = calm && (gtaStanding || calmT > 0.3);
  stopDiag(ped, resting, flags);
  if (resting) {
    vel.x = 0; vel.y = 0; vel.z = 0;
    Memory.WriteFloat(ped + O_MOVESPEED, 0, false); Memory.WriteFloat(ped + O_MOVESPEED + 4, 0, false);
    lastWritten = { x: 0, y: 0 }; lastPos = { x: c.x, y: c.y }; lastTs = ts;
    const target = ducking ? 1 : 0;
    duckFrac += Math.sign(target - duckFrac) * Math.min(Math.abs(target - duckFrac), dt / DUCK_TIME);
    eyeZ = EYE_STAND + (EYE_DUCK - EYE_STAND) * duckFrac;
    return { onGround, ducking, speed: 0, surf: false };
  }
  if (flags & 1) Memory.WriteU8(ped + O_PEDFLAGS, (flags & ~1) | 2, false);
  Memory.WriteFloat(ped + O_MOVESPEED, vel.x * UPS_TO_GTA, false);
  Memory.WriteFloat(ped + O_MOVESPEED + 4, vel.y * UPS_TO_GTA, false);
  // GTA subtracts its own gravity (0.008/step) before moving: pre-compensate so our vz is what is used
  let vzOut = vel.z;
  if (onGround && ground && ground.nz > 0.05 && ground.nz < 0.999) vzOut = -(vel.x * ground.nx + vel.y * ground.ny) / ground.nz;   // along the ground plane
  if (onGround && ground && ground.d > 0.12) vzOut = Math.min(vzOut, 0) + Math.max(-((ground.d - 0.05) / Math.max(dt, 0.005)) / U2M, -2000);   // stick to the ground (downhill)
  Memory.WriteFloat(ped + O_MOVESPEED + 8, vzOut * UPS_TO_GTA + 0.008 * ts, false);
  // airborne on a ramp / surf (or the first frame after leaving one = the crest launch): remember where GTA should
  // put us, so the next frame can give back what its collision step swallowed
  const slope = cts.some(k => k.nz >= 0.7 && k.nz < 0.999);
  const ceil = cts.some(k => k.nz < -0.7);
  const onRamp = !onGround && !jumped && (steep || slope) && !walls.length && !ceil;
  if (onRamp || (rampGrace > 0 && !onGround && vel.z > 0 && !walls.length && !ceil)) {
    rampTrack = { x: c.x, y: c.y, z: c.z, ex: vel.x * UPS_TO_GTA * ts, ey: vel.y * UPS_TO_GTA * ts, ez: vzOut * UPS_TO_GTA * ts };
    rampGrace = onRamp ? 3 : rampGrace - 1;
  } else { rampTrack = null; rampGrace = 0; }
  lastWritten = { x: vel.x, y: vel.y };
  lastPos = { x: c.x, y: c.y }; lastTs = ts;

  const target = ducking ? 1 : 0;
  duckFrac += Math.sign(target - duckFrac) * Math.min(Math.abs(target - duckFrac), dt / DUCK_TIME);
  eyeZ = EYE_STAND + (EYE_DUCK - EYE_STAND) * duckFrac;
  return { onGround, ducking, speed: Math.hypot(vel.x, vel.y), surf: !!steep && !onGround };
}

