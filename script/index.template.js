function friction(dt) {
  const p = preset();
  const speed = Math.hypot(vel.x, vel.y);
  if (speed < 0.1) return;
  const control = speed < p.stopspeed ? p.stopspeed : speed;
  const ns = Math.max(speed - control * p.friction * dt, 0) / speed;
  vel.x *= ns; vel.y *= ns;
}
function accelerate(wx, wy, wishspeed, accel, dt) {
  const add = wishspeed - (vel.x * wx + vel.y * wy);
  if (add <= 0) return;
  const acc = Math.min(accel * dt * wishspeed, add);
  vel.x += acc * wx; vel.y += acc * wy;
}
function airAccelerate(wx, wy, wishspeed, accel, dt) {
  const add = Math.min(wishspeed, AIR_SPEED_CAP) - (vel.x * wx + vel.y * wy);
  if (add <= 0) return;
  const acc = Math.min(accel * wishspeed * dt, add);
  vel.x += acc * wx; vel.y += acc * wy;
}
