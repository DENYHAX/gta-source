      if (saveEcx) b.push(0x51);                                        // push ecx
      b.push(0x31, 0xD2);                                               // xor edx, edx  (edx = ped to re-hide, 0 = none)
      b.push(0xA1); u32(FLAG); b.push(0x85, 0xC0, 0x74, 0x1E);          // mov eax,[FLAG]; test; jz -> push edx
      b.push(0xA1); u32(BEAT); b.push(0x3B, 0x05); u32(A_FRAME_COUNTER); b.push(0x75, 0x11);   // beat == frame? else -> push edx
