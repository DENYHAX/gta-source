function fireBullet(eye, dir, spread, dmg, range) {
  const x = rnd(-0.5, 0.5) + rnd(-0.5, 0.5), y = rnd(-0.5, 0.5) + rnd(-0.5, 0.5);
  const dx = dir.f.x + x * spread * dir.r.x + y * spread * dir.u.x;
  const dy = dir.f.y + x * spread * dir.r.y + y * spread * dir.u.y;
  const dz = dir.f.z + x * spread * dir.r.z + y * spread * dir.u.z;
  const l = Math.hypot(dx, dy, dz);
  const ped = Memory.ReadU32(A_PLAYER_PED, false);
  if (ped && !WEAPONS[cur].melee) {
    try { if (gtaShot(ped, eye.x, eye.y, eye.z, eye.x + dx / l * range, eye.y + dy / l * range, eye.z + dz / l * range, dmg)) return; }
    catch (e) { if (!fireBullet.warned) { fireBullet.warned = true; log("[cssource] gtaShot error, falling back to FireSingleBullet: " + e); } }
  }
  World.FireSingleBullet(eye.x + dx / l * 0.45, eye.y + dy / l * 0.45, eye.z + dz / l * 0.45,
                         eye.x + dx / l * range, eye.y + dy / l * range, eye.z + dz / l * range, dmg);
}

