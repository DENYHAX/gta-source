// ---- keep the Windows cursor inside the game window (needs the [dll] permission) ----
let win = null;
function winInit() {
  if (win !== null) return;
  win = false;
  try {
    const u = DynamicLibrary.Load("user32.dll"), k = DynamicLibrary.Load("kernel32.dll");
    if (!u || !k) { log("[cssource] cannot load user32/kernel32 (dll permission?)"); return; }
    win = { clip: u.getProcedure("ClipCursor"), fg: u.getProcedure("GetForegroundWindow"), tid: u.getProcedure("GetWindowThreadProcessId"),
            cr: u.getProcedure("GetClientRect"), c2s: u.getProcedure("ClientToScreen"), buf: Memory.Allocate(32),
            dpi: u.getProcedure("SetThreadDpiAwarenessContext"),
            mon: u.getProcedure("MonitorFromWindow"), mi: u.getProcedure("GetMonitorInfoW"), mbuf: Memory.Allocate(48) };   // Win10+: physical pixels (Windows scaling cut off the right side)
    win.pid = Memory.CallFunctionReturn(k.getProcedure("GetCurrentProcessId"), 0, 0);
  } catch (e) { log("[cssource] cursor clip unavailable: " + e); win = false; }
}
let clipTick = 0, clipped = false;
function clipCursor(on) {
  winInit();
  if (!win) return;
  if (!on) { if (clipped) { Memory.CallFunction(win.clip, 1, 0, 0); clipped = false; } return; }
  if (clipped && (clipTick++ % 10) !== 0) return;
  const hwnd = Memory.CallFunctionReturn(win.fg, 0, 0);
  if (!hwnd) return;
  Memory.CallFunctionReturn(win.tid, 2, 0, hwnd, win.buf + 16);
  if (Memory.ReadU32(win.buf + 16, false) !== win.pid) { clipped = false; return; }
  const prevCtx = win.dpi ? Memory.CallFunctionReturn(win.dpi, 1, 0, -4) : 0;   // DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2
  Memory.CallFunctionReturn(win.cr, 2, 0, hwnd, win.buf);
  Memory.CallFunctionReturn(win.c2s, 2, 0, hwnd, win.buf);
  Memory.CallFunctionReturn(win.c2s, 2, 0, hwnd, win.buf + 8);
  // never let the clip rect leave the monitor the game is on (a window bigger than the screen let the cursor
  // slide onto the next monitor on the right)
  if (win.mon && win.mi) {
    const hmon = Memory.CallFunctionReturn(win.mon, 2, 0, hwnd, 2);
    if (hmon) {
      Memory.WriteU32(win.mbuf, 40, false);
      if (Memory.CallFunctionReturn(win.mi, 2, 0, hmon, win.mbuf)) {
        const ml = Memory.ReadI32(win.mbuf + 4, false), mt = Memory.ReadI32(win.mbuf + 8, false);
        const mr = Memory.ReadI32(win.mbuf + 12, false), mb = Memory.ReadI32(win.mbuf + 16, false);
        const l = Math.max(Memory.ReadI32(win.buf, false), ml), t = Math.max(Memory.ReadI32(win.buf + 4, false), mt);
        const r = Math.min(Memory.ReadI32(win.buf + 8, false), mr), b = Math.min(Memory.ReadI32(win.buf + 12, false), mb);
        if (r - l > 100 && b - t > 100) {
          // keep a small margin from the edges
          Memory.WriteI32(win.buf, l + 2, false); Memory.WriteI32(win.buf + 4, t + 2, false);
          Memory.WriteI32(win.buf + 8, r - 2, false); Memory.WriteI32(win.buf + 12, b - 2, false);
        }
      }
    }
  }
  Memory.CallFunction(win.clip, 1, 0, win.buf);
  if (!win.logged) { win.logged = true; log("[cssource] cursor clip " + Memory.ReadI32(win.buf, false) + "," + Memory.ReadI32(win.buf + 4, false) + " - " + Memory.ReadI32(win.buf + 8, false) + "," + Memory.ReadI32(win.buf + 12, false)); }
  if (win.dpi && prevCtx) Memory.CallFunctionReturn(win.dpi, 1, 0, prevCtx);
  clipped = true;
}

// ------------------------- PEDS THAT DO NOT BLOCK THE BHOP ----------
// Mission / group peds warp next to the player and stand in the way. While bhopping we set their
// CPhysical::m_pEntityIgnoredCollision (+0x128) to the player: GTA then skips the push between the two
// (the same thing it does for a ped getting out of a car). GTA clears it by itself once they no longer touch.
const A_PED_POOL = 0xB74490, PED_POOL_ELEM = 0x7C4, O_IGNORED_COL = 0x128, O_CREATED_BY = 0x484;
let groupPeds = new Set(), groupT = -1;
function refreshGroup() {
  groupPeds = new Set();
  try {
    const g = player.getGroup();
    for (let i = 0; i < 7; i++) {
      let m = null;
      try { m = g.getMember(i); } catch (e) { m = null; }
      if (m && Char.DoesExist(m)) { const pp = Memory.GetPedPointer(m); if (pp) groupPeds.add(pp); }
    }
  } catch (e) {}
}
function ghostPeds(ped, mv) {
  if (!CFG.ghostPeds) return;
  if (!(mv.speed > CFG.ghostSpeed || (!mv.onGround && mv.speed > 100))) return;
  if (now - groupT > 0.5 || groupT < 0) { refreshGroup(); groupT = now; }
  const pool = Memory.ReadU32(A_PED_POOL, false); if (!pool) return;
  const objs = Memory.ReadU32(pool, false), map = Memory.ReadU32(pool + 4, false), size = Memory.ReadI32(pool + 8, false);
  if (!objs || !map || size <= 0 || size > 1000) return;
  const mat = Memory.ReadU32(ped + 0x14, false); if (!mat) return;
  const px = Memory.ReadFloat(mat + 0x30, false), py = Memory.ReadFloat(mat + 0x34, false), pz = Memory.ReadFloat(mat + 0x38, false);
  const all = CFG.ghostPeds === "all";
  for (let i = 0; i < size; i++) {
    if (Memory.ReadU8(map + i, false) & 0x80) continue;        // free slot
    const p = objs + i * PED_POOL_ELEM;
    if (p === ped) continue;
    if (!all && Memory.ReadU8(p + O_CREATED_BY, false) !== 2 && !groupPeds.has(p)) continue;   // 2 = mission ped
    if (Memory.ReadU8(p + O_PEDFLAGS + 1, false) & 1) continue;  // bInVehicle: leave car peds alone
    const ign = Memory.ReadU32(p + O_IGNORED_COL, false);
    if (ign && ign !== ped) continue;                            // GTA is using it (e.g. getting out of a car)
    const m = Memory.ReadU32(p + 0x14, false); if (!m) continue;
    const dx = Memory.ReadFloat(m + 0x30, false) - px, dy = Memory.ReadFloat(m + 0x34, false) - py, dz = Memory.ReadFloat(m + 0x38, false) - pz;
    if (dx * dx + dy * dy + dz * dz < 36) Memory.WriteU32(p + O_IGNORED_COL, ped, false);
  }
}

// ------------------------- LOW CLOUDS ---------------------------------
// CClouds::Render draws the low clouds as flat 2D sprites (0x71401E..0x71422A). At a wide FOV they slide
// across the sky when you turn. Skip just that block with a jmp (moon, stars, rainbow and the sky stay).
const A_LOWCLOUDS = 0x71401E, LC_ORIG = [0xD9, 0x05, 0x00, 0x13, 0xC8], LC_SKIP = [0xE9, 0x07, 0x02, 0x00, 0x00];
function setLowClouds(on) {
  try {
    const bytes = [0, 1, 2, 3, 4].map(i => Memory.ReadU8(A_LOWCLOUDS + i, true));
    const isOrig = bytes.every((v, i) => v === LC_ORIG[i]), isSkip = bytes.every((v, i) => v === LC_SKIP[i]);
    if (!isOrig && !isSkip) { if (!setLowClouds.warned) { setLowClouds.warned = true; log("[cssource] cloud patch: unknown bytes, skipped"); } return; }
    if (on === isOrig) return;
    const w = on ? LC_ORIG : LC_SKIP;
    for (let i = 0; i < 5; i++) Memory.WriteU8(A_LOWCLOUDS + i, w[i], true);
  } catch (e) { log("[cssource] cloud patch error: " + e); }
}

// ------------------------- FPS CAP IN VEHICLES ----------------------
